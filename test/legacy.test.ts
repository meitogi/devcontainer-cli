// thing: templates/v2/ when the monorepo is present, and the top-level entry
// lists of the three v2 trees measured on 2026-09-23 (the dogfood, symptems,
// ragnarokonline) baked below — N=3 is the first time this project could
// tell "a v2 tree" from "this v2 tree".

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { detectLegacy, inventoryLegacy, LEGACY_LAYOUT, readLegacyMarker, type LegacyCategory } from '../src/lib/legacy.js'
import { PACKAGE_ROOT } from '../src/lib/version.js'

const MONOREPO_V2 = join(PACKAGE_ROOT, '..', '..', 'templates', 'v2')

const MARKER = `# Auto-generated by install.sh v2.0.0 — do not edit.
VERSION="2.0.0"
PROJECT_ID="symptems"
PROJECT_DISPLAY_NAME="Symptems"
PROJECT_TYPE="node"
CLAUDE_CREDS_VOLUME="claude-creds-shared-boa"
INSTALLED_AT="2026-05-29T08:10:59Z"
`

function scratch(): { dir: string; cleanup: () => void } {
	const dir = mkdtempSync(join(tmpdir(), 'devc-legacy-'))
	return { dir, cleanup: () => rmSync(dir, { recursive: true, force: true }) }
}

test('readLegacyMarker: the six install.sh keys, quotes stripped, major from VERSION', () => {
	const { dir, cleanup } = scratch()
	try {
		const file = join(dir, '.configured-setup')
		writeFileSync(file, MARKER, 'utf8')
		const marker = readLegacyMarker(file)
		assert.ok(marker)
		assert.equal(marker.version, '2.0.0')
		assert.equal(marker.major, '2')
		assert.deepEqual(marker.fields, {
			VERSION: '2.0.0',
			PROJECT_ID: 'symptems',
			PROJECT_DISPLAY_NAME: 'Symptems',
			PROJECT_TYPE: 'node',
			CLAUDE_CREDS_VOLUME: 'claude-creds-shared-boa',
			INSTALLED_AT: '2026-05-29T08:10:59Z',
		})
		// Unquoted values and a missing VERSION line.
		writeFileSync(file, 'PROJECT_ID=bare\n', 'utf8')
		assert.deepEqual(readLegacyMarker(file), { version: '', major: '?', fields: { PROJECT_ID: 'bare' } })
		assert.equal(readLegacyMarker(join(dir, 'absent')), null)
	} finally {
		cleanup()
	}
})

test('detectLegacy: Dockerfile.base names v2 first; the marker alone names its own major; neither is null', () => {
	const { dir, cleanup } = scratch()
	try {
		const dc = join(dir, '.devcontainer')
		mkdirSync(dc)
		assert.equal(detectLegacy(dir), null)
		writeFileSync(join(dc, '.configured-setup'), 'VERSION="1.3.0"\n', 'utf8')
		assert.match(detectLegacy(dir)?.found ?? '', /^a v1 layout made by install\.sh \(\.configured-setup is present\)$/)
		writeFileSync(join(dc, 'Dockerfile.base'), 'FROM node\n', 'utf8')
		const both = detectLegacy(dir)
		assert.equal(both?.found, 'a v2 layout made by install.sh (Dockerfile.base is present)')
		assert.equal(both?.marker?.major, '1', 'the marker is still read when Dockerfile.base wins')
	} finally {
		cleanup()
	}
})

