test('the three real v2 trees: every entry the template made is classified, and only their own land in "yours"', () => {
	for (const name in REAL_TREES) {
		const tree = REAL_TREES[name] as { entries: string[]; yours: string[] }
		const yours = tree.entries.filter((entry) => (LEGACY_LAYOUT[entry]?.category ?? 'yours') === 'yours').sort()
		assert.deepEqual(yours, [...tree.yours].sort(), name)
	}
})

test('inventoryLegacy reads the lifecycle lines, the FROM, the loader and .env — and marks directories', () => {
	const { dir, cleanup } = scratch()
	try {
		const dc = join(dir, '.devcontainer')
		mkdirSync(join(dc, 'skills'), { recursive: true })
		mkdirSync(join(dc, 'orchestration'))
		writeFileSync(join(dc, 'Dockerfile.base'), 'FROM node\n', 'utf8')
		writeFileSync(join(dc, 'Dockerfile'), '# slim layer\nARG X=1\nFROM claude-devcontainer-base:${CLAUDE_CODE_VERSION}-${DC_PROJECT}\nRUN true\n', 'utf8')
		writeFileSync(
			join(dc, 'devcontainer.json'),
			'{\n  // a comment\n  "initializeCommand": "bash .devcontainer/initialize.sh",\n  "onCreateCommand": "bash .devcontainer/on-create.sh",\n  "postStartCommand": "bash .devcontainer/post-start.sh",\n}\n',
			'utf8',
		)
		writeFileSync(join(dc, 'skills', 'sync-skills.sh'), '#!/bin/bash\n', 'utf8')
		writeFileSync(join(dc, '.env'), 'CLAUDE_CREDS_VOLUME=claude-creds-shared-boa\n', 'utf8')

		const tree = inventoryLegacy(dir)
		assert.equal(tree.initializeCommand, 'bash .devcontainer/initialize.sh')
		assert.deepEqual(tree.lifecycle, {
			onCreateCommand: 'bash .devcontainer/on-create.sh',
			postCreateCommand: null,
			postStartCommand: 'bash .devcontainer/post-start.sh',
		})
		assert.equal(tree.stitchuBlock, false)
		assert.equal(tree.dockerfileFrom, 'FROM claude-devcontainer-base:${CLAUDE_CODE_VERSION}-${DC_PROJECT}')
		assert.equal(tree.loader, true)
		assert.deepEqual(tree.env, { CLAUDE_CREDS_VOLUME: 'claude-creds-shared-boa' })
		const byName = Object.fromEntries(tree.entries.map((entry) => [entry.name, entry.category])) as Record<string, LegacyCategory>
		assert.equal(byName['skills/'], 'config')
		assert.equal(byName['orchestration/'], 'yours')
		assert.equal(byName['Dockerfile.base'], 'image')
		assert.equal(byName['.env'], 'config')
	} finally {
		cleanup()
	}
})

test('the claude/ note says the image ships no patcher (4.1i), not the reverse', () => {
	// The three real trees carry v2 copies of the shared patchers under
	// claude/vscode-ext-patchs/; ext-patches-sync merges local patchers over
	// the pinned set, so the note has to send them away, not call them shipped.
	const note = LEGACY_LAYOUT['claude']?.note ?? ''
	assert.match(note, /the image ships no patcher/)
	assert.doesNotMatch(note, /ship in the image/)
})
